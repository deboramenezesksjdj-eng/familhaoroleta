-- Tabela de resgates do painel administrativo
create table if not exists public.redemptions (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nome text,
  cpf text,
  whatsapp text,
  endereco text,
  banco text,
  agencia text,
  conta text,
  premio text default 'R$ 50.000',
  status text default 'pendente',
  data text,
  hora text,
  timestamp timestamptz,
  protocolo text
);

-- Permite leitura pública (formulário) e escrita pública (envio de resgate).
-- A service_role key usada pelo painel ignora RLS.
alter table public.redemptions enable row level security;

drop policy if exists "permitir leitura" on public.redemptions;
create policy "permitir leitura" on public.redemptions for select to anon using (true);

drop policy if exists "permitir insercao" on public.redemptions;
create policy "permitir insercao" on public.redemptions for insert to anon with check (true);
